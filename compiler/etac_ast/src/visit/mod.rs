//! Traversing the AST with visitors.
//!
//! Useful for writing passes over the tree. A visitor overrides the hooks for the nodes it cares about, and the rest
//! of the tree is walked through automatically. Thus a pass only has to mention the parts it
//! handles.
//!
//! # Traits
//!
//! - [`Visitor`]: Has hooks per ast node. This is what passes implement.
//! - [`Visitable`]: Ast dispatch. `node.visit(visitor)` calls `visitor.visit_node(node)`. Some containers also
//!   implement this.
//! - [`Walkable`]: Recursion. `node.walk(visitor)` calls `.visit(v)` on each of the node's children, in a [fixed
//!   order](crate::walk#traversal-order).
//!
//! A traversal typically looks like the following:
//!
//! ```text
//! node.visit(visitor) --> visitor.visit_foo(node) --> node.walk(visitor) --> child.visit(visitor) --> ...
//! (dispatch)              (pass logic)                (recursion)            (dispatch)
//! ```
//!
//! # Variants
//!
//! Each trait has 3 variants, depending on how the visitor gets hold of the tree:
//!
//! | Flavor   | Implement            | Hooks look like           | Dispatch           | Recursion         |
//! |----------|----------------------|---------------------------|--------------------|-------------------|
//! | Borrowed | [`Visitor<'ast>`][V] | `visit_foo(&'ast Foo)`    | [`Visitable`]      | [`Walkable`]      |
//! | Mutable  | [`VisitorMut`]       | `visit_foo_mut(&mut Foo)` | [`VisitableMut`]   | [`WalkableMut`]   |
//! | Owned    | [`VisitorOwned`]     | `visit_foo_owned(Foo)`    | [`VisitableOwned`] | [`WalkableOwned`] |
//!
//! Each operate exactly the same except for name and ownership of the tree.
//!
//! ## Borrowed Visitors
//! The default choice for analysis passes, and the only variant that can hold on to references into the tree.
//!
//! ## Mutable Visitors
//! Visitors that can edit nodes in place, including replacing a whole node with `*node = ...`. Ex: folding
//! additions of integer literals.
//!
//! ## Owned Visitors
//! Visitors that can take the tree by value, and each hook gets ownership of its node. They are for passes that
//! consume the AST, such as lowering it into another representation, and moving data out of it without cloning
//! (AST nodes aren't `Clone`). Once a hook has taken its node apart it can't `walk_owned` it any more, so it visits
//! the parts it needs itself.
//!
//! Slices can't be moved out of, so `[T]` is not [`VisitableOwned`]; `Vec<T>` is.
//!
//! # Adding a node type
//!
//! The traits and most of their impls are generated by macros, so a new AST node type needs an entry in two places:
//!
//! 1. The `ast_visitor!` list in `visit/visitor.rs`. This generates the `visit_new_node`, `visit_new_node_mut` and
//!    `visit_new_node_owned` hooks, and the [`Visitable`] impls that dispatch to them.
//! 2. `walk/walk_impl.rs`: list the node's children with `impl_walk!`, or declare it a leaf with `atom!`. One
//!    `impl_walk!` body covers all three flavors.
//!
//! Then visit the new node from the `impl_walk!` of every node that contains it, and check the
//! [printers](crate::display), which visit some children by hand. The walker destructures every node exhaustively, so
//! adding a field to an existing node is a compile error in `walk_impl.rs` until the field is either visited or
//! explicitly ignored (like `span: _`).
//!
